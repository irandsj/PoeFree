using PoeFree.Core.Patching;

namespace PoeFree.App;

/// <summary>Tiny localisation table (English / Português). Missing Portuguese strings fall back to English.</summary>
public sealed class Loc {
	public static Loc Instance { get; } = new();

	public string Language { get; private set; } = "en";

	public static readonly string[] Languages = ["en", "pt"];

	public void SetLanguage(string lang) => Language = Languages.Contains(lang) ? lang : "en";

	public string this[string key] => T(key);

	public static string T(string key) {
		if (Instance.Language == "pt" && Pt.TryGetValue(key, out var pt))
			return pt;
		return En.TryGetValue(key, out var en) ? en : key;
	}

	public static string F(string key, params object[] args) => string.Format(T(key), args);

	public static string PatchName(Patch p) => Instance.Language == "pt" && Pt.TryGetValue("patch." + p.Id, out var n) ? n : p.Name;
	public static string PatchDescription(Patch p) => Instance.Language == "pt" && Pt.TryGetValue("patch." + p.Id + ".desc", out var d) ? d : p.Description;

	public static string Category(PatchCategory c) => T("cat." + c);

	public static string HealthDetail(Core.Diagnostics.PatchHealth h) => h.Reason switch {
		Core.Diagnostics.HealthReason.None => F("health.detail.ok", h.Changes, h.Targets),
		Core.Diagnostics.HealthReason.NoTargets => T("health.detail.noTargets"),
		Core.Diagnostics.HealthReason.NoChanges => F("health.detail.noChanges", h.Targets),
		Core.Diagnostics.HealthReason.Errors => F("health.detail.errors", string.Join("; ", h.Errors.Take(2))),
		_ => T("health.detail.unsupported"),
	};

